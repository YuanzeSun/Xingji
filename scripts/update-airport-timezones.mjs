import { find } from 'geo-tz';
import { writeFile } from 'node:fs/promises';
import { AIRPORTS } from '../src/data/location-reference.js';
import { AIRPORT_POINTS } from '../src/data/map-reference.js';

const groups = new Map(), missing = [];
const domestic = { CN: 'Asia/Shanghai', HK: 'Asia/Hong_Kong', MO: 'Asia/Macau', TW: 'Asia/Taipei' };
for (const [code, , country] of AIRPORTS) {
  const point = AIRPORT_POINTS[code];
  const zone = domestic[country] || (point && find(point[1], point[0])[0]);
  if (!zone) { missing.push(code); continue; }
  if (!groups.has(zone)) groups.set(zone, []);
  groups.get(zone).push(code);
}
if (missing.length) throw new Error('Missing airport time zones: ' + missing.join(', '));
const entries = [...groups].sort(([a], [b]) => a.localeCompare(b)).map(([zone, codes]) => [zone, codes.sort().join(' ')]);
await writeFile(new URL('../src/data/airport-timezones.js', import.meta.url), `// Generated by scripts/update-airport-timezones.mjs using geo-tz 8.1.11.\n// Airport coordinates: OurAirports (Public Domain). Timezone boundaries: ODbL; see THIRD_PARTY_NOTICES.md.\nexport const AIRPORT_TIMEZONES=Object.fromEntries(${JSON.stringify(entries)}.flatMap(([zone,codes])=>codes.split(' ').map(code=>[code,zone])));\n`);
console.log(`Generated time zones for ${AIRPORTS.length} airports (${entries.length} zones).`);
