import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const cache = new URL('../.preview/airline-labels.json', import.meta.url);
const query = `SELECT ?airline ?iata ?icao ?english ?chinese ?simplified ?alias WHERE {
 ?airline wdt:P229 ?iata.
 OPTIONAL { ?airline wdt:P230 ?icao. }
 OPTIONAL { ?airline rdfs:label ?english. FILTER(LANG(?english)="en") }
 OPTIONAL { ?airline rdfs:label ?chinese. FILTER(LANG(?chinese)="zh") }
 OPTIONAL { ?airline rdfs:label ?simplified. FILTER(LANG(?simplified)="zh-hans") }
 OPTIONAL { ?airline skos:altLabel ?alias. FILTER(LANG(?alias) IN ("zh","zh-hans","zh-hant")) }
}`;
await mkdir(new URL('../.preview/', import.meta.url), { recursive: true });
let source;
if (process.argv.includes('--from-cache')) source = await readFile(cache, 'utf8');
else {
  const url = new URL('https://query.wikidata.org/sparql'); url.searchParams.set('query', query); url.searchParams.set('format', 'json');
  const response = await fetch(url, { headers: { Accept: 'application/sparql-results+json', 'User-Agent': 'Xingji-reference-generator/1.0 (https://github.com/YuanzeSun/Xingji)' }, signal: AbortSignal.timeout(60000) });
  if (!response.ok) throw new Error('Airline source: ' + response.status);
  source = await response.text(); await writeFile(cache, source);
}
const airlines = new Map();
for (const binding of JSON.parse(source).results.bindings) {
  const id = binding.airline.value.split('/').at(-1), iata = binding.iata.value.toUpperCase();
  if (!/^[A-Z0-9]{2}$/.test(iata)) continue;
  if (!airlines.has(id)) airlines.set(id, { codes: new Set(), names: new Set(), en: binding.english?.value || '', zh: binding.simplified?.value || binding.chinese?.value || '' });
  const row = airlines.get(id); row.codes.add(iata);
  if (binding.icao?.value && /^[A-Z]{3}$/.test(binding.icao.value)) row.codes.add(binding.icao.value);
  if (binding.chinese?.value) row.names.add(binding.chinese.value);
  if (binding.alias?.value) row.names.add(binding.alias.value);
}
const rows = [...airlines].map(([id, row]) => [id, row.zh, row.en, [...row.codes].sort(), [...row.names].sort()]).filter(row => row[1] || row[2]);
if (rows.length < 700) throw new Error('Airline reference is incomplete');
await writeFile(new URL('../src/data/airline-reference.js', import.meta.url), `// Wikidata structured data, CC0-1.0. Generated by scripts/update-airlines.mjs.\nexport const AIRLINE_REFERENCE=${JSON.stringify({ date: new Date().toISOString().slice(0, 10), source: 'https://www.wikidata.org/wiki/Property:P229', hash: createHash('sha256').update(source).digest('hex') })};\nexport const AIRLINES=${JSON.stringify(rows)};\n`);
console.log(`Generated ${rows.length} airlines.`);
