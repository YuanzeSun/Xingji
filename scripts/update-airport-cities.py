"""Build airport service-city identities from CAAC's city/airport reference."""
from argparse import ArgumentParser
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.parse import urljoin
from urllib.request import Request, urlopen
import json
import re
import xml.etree.ElementTree as ET
import zipfile

root = Path(__file__).resolve().parents[1]
parser = ArgumentParser()
parser.add_argument('--from-cache', action='store_true')
args = parser.parse_args()
source = 'https://www.caac.gov.cn/XXGK/XXGK/TJSJ/202602/t20260226_230119.html'
cache = root / '.preview/airport-city-reference'
cache.mkdir(parents=True, exist_ok=True)
path = cache / 'caac-2025.xlsx'
if not args.from_cache:
    def fetch(url):
        return urlopen(Request(url, headers={'User-Agent': 'Xingji airport service-city reference'}), timeout=30).read()
    html = fetch(source).decode('utf-8')
    links = re.findall(r'href="([^"]+\.xlsx)"[^>]*>(.*?)</a>', html, re.S)
    url = urljoin(source, next(link for link, label in links if '吞吐量排名' in label))
    path.write_bytes(fetch(url))
data = path.read_bytes()
ns = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
with zipfile.ZipFile(BytesIO(data)) as archive:
    strings = [''.join(node.itertext()) for node in ET.fromstring(archive.read('xl/sharedStrings.xml')).findall('s:si', ns)]
    names = []
    for row in ET.fromstring(archive.read('xl/worksheets/sheet1.xml')).findall('.//s:row', ns):
        cells = {}
        for cell in row.findall('s:c', ns):
            value = cell.find('s:v', ns)
            if value is not None:
                cells[re.sub(r'\d', '', cell.get('r'))] = strings[int(value.text)] if cell.get('t') == 's' else value.text
        name = cells.get('A', '').strip()
        if name not in ['合计', '机场'] and re.fullmatch(r'[\u3400-\u9fff]+(?:/[\u3400-\u9fff]+)?', name) and cells.get('B', '').isdigit():
            names.append(name)
if len(names) < 260:
    raise ValueError('CAAC airport city reference is incomplete')
normalize = lambda value: re.sub(r'国际|机场|\s|/', '', value)
official = {normalize(name): name.split('/')[0] for name in names}
cities = sorted(set(official.values()), key=lambda city: (-len(city), city))
def exported(file, name):
    return json.loads(re.search(r'^export const ' + name + r' = (.+);$', (root / file).read_text(encoding='utf-8'), re.M)[1])
airports = exported('src/data/location-reference.js', 'AIRPORTS')
labels = {row[0]: row[1:] for row in exported('src/data/airport-labels.js', 'AIRPORT_LABELS')}
output = {}
for code, _, country, _, aliases, *_ in airports:
    if country != 'CN':
        continue
    preferred, localized = labels.get(code, ['', []])
    choices = {official[normalize(name)] for name in [preferred, *localized, *aliases.split('|')] if normalize(name) in official}
    if len(choices) == 1:
        output[code] = choices.pop()
    elif not choices:
        city = next((city for city in cities if preferred.startswith(city)), '')
        if city:
            output[code] = city
for code, city in [('XNN', '西宁'), ('LXA', '拉萨'), ('XIY', '西安'), ('YIW', '义乌')]:
    if output.get(code) != city:
        raise ValueError('Unexpected service city: ' + code)
metadata = {'source': source, 'period': 2025, 'officialAirports': len(names), 'matchedAirports': len(output), 'sha256': sha256(data).hexdigest(), 'match': 'Exact localized airport identity, then official name-city prefix; physical municipality is not used as the named city.'}
content = '// Generated by scripts/update-airport-cities.py. Public airport identities only.\n'
content += 'export const AIRPORT_CITY_REFERENCE = ' + json.dumps(metadata, ensure_ascii=False) + ';\n'
content += 'export const AIRPORT_SERVICE_CITIES = ' + json.dumps(dict(sorted(output.items())), ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'src/data/airport-cities.js').write_text(content, encoding='utf-8')
print(json.dumps({'official': len(names), 'matched': len(output)}))
