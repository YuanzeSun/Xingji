import { writeFile } from 'node:fs/promises';

const source = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_populated_places.geojson';
const response = await fetch(source, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) throw new Error(`Populated places download failed: ${response.status}`);
const { features } = await response.json();
const rows = [];
for (const { properties, geometry } of features) {
  const { NAME, NAME_ZH, SCALERANK, ADM0CAP, POP_MAX } = properties;
  if (SCALERANK > 3 && ADM0CAP !== 1 && POP_MAX < 1_000_000) continue;
  if (geometry?.type !== 'Point' || !geometry.coordinates.every(Number.isFinite)) continue;
  const [lon, lat] = geometry.coordinates.map(value => Number(value.toFixed(5)));
  rows.push([NAME_ZH || NAME, lon, lat, SCALERANK]);
}
if (rows.length < 300) throw new Error('Populated places data appears incomplete');
rows.sort((a, b) => a[3] - b[3] || a[1] - b[1] || a[2] - b[2]);
await writeFile(new URL('../src/data/flight-map-cities.js', import.meta.url),
  `// Generated by scripts/update-flight-map-cities.mjs. Made with Natural Earth, public domain.\n// ${source}\nexport const FLIGHT_MAP_CITIES = [\n${rows.map(row => '  ' + JSON.stringify(row)).join(',\n')}\n];\n`);
