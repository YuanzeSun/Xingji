import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {createRecord} from '../src/model.js';
import {railQuery} from '../src/rail-lookup-model.js';
import {lookupRailDetails} from '../src/rail-data.js';
import {selectRailRoute} from '../src/rail-route.js';
import {loadRailLineNames} from '../src/rail-line-names.js';

const cached=process.argv.includes('--from-cache');
const date=process.argv.find(arg=>arg.startsWith('--date='))?.slice(7) || new Date().toISOString().slice(0,10);
const requests=[['G21','北京南','南京南'],['G7602','杭州东','南京南'],['Z83','北京','齐齐哈尔'],['G6203','广州南','深圳北'],['C2021','北京南','天津']];
const directory=new URL('../.preview/demo-references/',import.meta.url);
await mkdir(directory,{recursive:true});
const details={};
for(const [service,origin,destination] of requests){
  const file=new URL(service+'.json',directory),record=createRecord({service,origin,destination,departureDate:date});
  const result=cached ? JSON.parse(await readFile(file,'utf8')) : await lookupRailDetails(railQuery(record));
  if(!result.railRoute && service==='G7602'){
    const routeFile=new URL('G7602-route.json',directory);
    const payload=cached ? JSON.parse(await readFile(routeFile,'utf8')) : await fetch('https://rg-api.zenglingkun.cn/api/v2/mapLine?train=G7602').then(response=>response.json());
    // RailGo's separate station marker is misplaced. The two adjoining track
    // segments agree on the actual Yixing endpoint; retain their original geometry.
    const left=payload.data.train['杭州东-宜兴'].line.at(-1),right=payload.data.train['宜兴-溧水'].line[0];
    if(JSON.stringify(left)!==JSON.stringify(right))throw new Error('Yixing track endpoints no longer agree');
    payload.data.stations.find(stop=>Object.hasOwn(stop,'宜兴')).宜兴=left;
    result.railRoute=await loadRailLineNames(selectRailRoute(record,payload));
    if(!cached)await writeFile(routeFile,JSON.stringify(payload));
  }
  if(!result.railRoute?.segments.length || !result.railJourney?.stops.length || ![...(result.railRoute.lineLabels||[]),...(result.railRoute.fullRoute?.lineLabels||[])].length)throw new Error('Incomplete demo railway snapshot: '+service);
  delete result.partial;
  details[service]=result;
  await writeFile(file,JSON.stringify(result));
  console.log(service+': '+result.railJourney.stops.length+' stops, '+JSON.stringify(result.railRoute).length+' route bytes');
}
const metadata={sources:['https://api.railgo.dev/479755220e0','https://api.railgo.dev/479769351e0','https://fog.vicc.wang/rails'],services:requests.map(row=>row[0]),note:'Public timetable, rolling-stock and track snapshots. Demo passenger details and displayed journey dates are illustrative.'};
await writeFile(new URL('../src/data/demo-rail.js',import.meta.url),'// Generated by scripts/update-demo-rail.mjs. Public railway reference data only.\nexport const DEMO_RAIL_REFERENCE = '+JSON.stringify(metadata)+';\nexport const DEMO_RAIL_DETAILS = '+JSON.stringify(details)+';\n');
