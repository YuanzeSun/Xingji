import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { airportGeographySource } from './airport-geography.mjs';

const root = resolve(import.meta.dirname, '..');
const stationUrl = 'https://kyfw.12306.cn/otn/resources/js/framework/station_name.js';
const airportUrl = 'https://davidmegginson.github.io/ourairports-data/airports.csv';
const cached = process.argv.includes('--from-cache');
async function source(url, file) {
  if (cached) return readFile(resolve(root, '.preview', file), 'utf8');
  const response = await fetch(url, { signal: AbortSignal.timeout(45000) });
  if (!response.ok) throw new Error(`Reference download failed: ${response.status}`);
  return response.text();
}
function parseCsv(csv) {
  const rows = []; let row = [], cell = '', quoted = false;
  for (let i = 0; i < csv.length; i++) {
    const c = csv[i];
    if (c === '"') { if (quoted && csv[i + 1] === '"') { cell += '"'; i++; } else quoted = !quoted; }
    else if (c === ',' && !quoted) { row.push(cell); cell = ''; }
    else if ((c === '\n' || c === '\r') && !quoted) { if (c === '\r' && csv[i + 1] === '\n') i++; row.push(cell); if (row.some(Boolean)) rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (quoted) throw new Error('Unclosed CSV cell');
  row.push(cell); if (row.some(Boolean)) rows.push(row);
  return rows;
}
const [stationText, airportText] = await Promise.all([source(stationUrl, 'station_name.js'), source(airportUrl, 'airports.csv')]);
const stations = stationText.split('@').slice(1).map(s => s.split('|')).filter(s => s.length >= 8 && s[1] && s[7]).map(s => [s[1], s[7], s[2], s[3], s[4]]);
for (const [name, city] of [['清河', '北京'], ['清河城', '邢台'], ['上海虹桥', '上海']]) if (!stations.some(s => s[0] === name && s[1] === city)) throw new Error('Unexpected 12306 city field: ' + name);
const rows = parseCsv(airportText), header = rows.shift(), field = name => { const index = header.indexOf(name); if (index < 0) throw new Error('Missing airport field: ' + name); return index; };
const iata = field('iata_code'), city = field('municipality'), country = field('iso_country'), region = field('iso_region'), name = field('name'), keywords = field('keywords');
const airports = rows.filter(r => /^[A-Z]{3}$/.test(r[iata]) && r[city]).map(r => [r[iata], r[city].replace(/\s*\([^)]*\)\s*$/, '').trim(), r[country], r[name], r[keywords].split(',').map(s => s.trim()).filter(s => /\p{Script=Han}/u.test(s)).join('|'), r[region]]);
if (stations.length < 3000 || airports.length < 5000) throw new Error('Reference appears incomplete');
for (const [code, cityName] of [['PEK', 'Beijing'], ['SHA', 'Shanghai'], ['TFU', 'Chengdu']]) if (!airports.some(a => a[0] === code && a[1] === cityName)) throw new Error('Unexpected airport municipality: ' + code);
const metadata = { fetchedAt: new Date().toISOString().slice(0, 10), railway: { source: stationUrl, count: stations.length }, airports: { source: airportUrl, count: airports.length, license: 'Public Domain', documentation: 'https://ourairports.com/data/' } };
await mkdir(resolve(root, 'src/data'), { recursive: true });
await writeFile(resolve(root, 'src/data/airport-geography.js'), airportGeographySource(rows, header, airportText));
await writeFile(resolve(root, 'src/data/location-reference.js'), `// Generated by scripts/update-locations.mjs; reference geography only, no personal trips.\nexport const LOCATION_REFERENCE = ${JSON.stringify(metadata)};\n// Rail: name, city, telecode, pinyin, initials. Airport: IATA, municipality, country, name, Chinese aliases, region.\nexport const STATIONS = ${JSON.stringify(stations)};\nexport const AIRPORTS = ${JSON.stringify(airports)};\n`);
console.log(JSON.stringify(metadata));
