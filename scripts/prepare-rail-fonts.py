"""Build the rail station and Latin faces. Requires fonttools[woff].

Use --source-dir to reuse original CTAN files downloaded during font research.
Sources are pinned by SHA-256; Windows reference fonts are never bundled.
"""
import argparse
import json
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen

from fontTools import subset
from fontTools.pens.basePen import NullPen
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source-dir', type=Path)
args = parser.parse_args()
SOURCES = [
    ('fandol/FandolHei-Regular.otf',
     '4afa97aa8751e0118617df88272b58d43691b5cffb7ea024c4580496e9f34d28',
     'Xingji Rail Hei', 'ticket-rail-hei.woff2', 1),
    ('tex-gyre/opentype/texgyretermes-regular.otf',
     'cc3fe7c707b81428d23d54df3eadd9228a2bf6a4d43125d94df56f5f63134659',
     'Xingji Rail Serif', 'ticket-rail-serif.woff2', 1),
    ('tex-gyre/opentype/texgyretermes-bold.otf',
     '2fb3e952065fa153c7e4e64e04b98b9d79225739b6025aa3f0f0782d299ff61e',
     'Xingji Rail Narrow', 'ticket-rail-narrow.woff2', .72),
    ('tex-gyre/opentype/texgyretermes-bold.otf',
     '2fb3e952065fa153c7e4e64e04b98b9d79225739b6025aa3f0f0782d299ff61e',
     'Xingji Rail Pinyin', 'ticket-rail-pinyin.woff2', .61),
]

for source, digest, family, output, width in SOURCES:
    if args.source_dir:
        data = (args.source_dir / Path(source).name).read_bytes()
    else:
        with urlopen('https://mirrors.ibiblio.org/CTAN/fonts/' + source, timeout=45) as response:
            data = response.read()
    if sha256(data).hexdigest() != digest:
        raise ValueError('Unexpected source font: ' + source)
    font = TTFont(BytesIO(data), recalcTimestamp=False)
    if 'texgyre' in source:
        options = subset.Options()
        options.name_IDs = ['*']
        options.name_legacy = True
        options.name_languages = ['*']
        options.desubroutinize = True
        options.layout_features = []
        subsetter = subset.Subsetter(options=options)
        # Station pinyin, sale codes, train identifiers and historical fares.
        subsetter.populate(unicodes=range(32, 127))
        subsetter.subset(font)
    if width != 1:
        glyphs = font.getGlyphSet()
        top = font['CFF '].cff.topDictIndex[0]
        outlines = {}
        for name in font.getGlyphOrder():
            advance, bearing = font['hmtx'][name]
            pen = T2CharStringPen(round(advance * width), None)
            glyphs[name].draw(TransformPen(pen, (width, 0, 0, 1, 0, 0)))
            outlines[name] = pen.getCharString(private=top.Private, globalSubrs=font['CFF '].cff.GlobalSubrs)
            font['hmtx'][name] = (round(advance * width), round(bearing * width))
        for name, outline in outlines.items():
            top.CharStrings[name] = outline
        # T2CharStringPen emits absolute widths. The original font's nominal
        # width must not be added again by an OpenType renderer.
        top.Private.nominalWidthX = 0
        top.Private.defaultWidthX = 0
        for name, outline in outlines.items():
            outline.draw(NullPen())
            if outline.width != font['hmtx'][name][0]:
                raise ValueError('CFF and hmtx advances differ: ' + name)
    # A separate family lets the bold, condensed pinyin outlines be selected
    # explicitly without browser-synthesized bold or platform font substitution.
    for name_id in [1, 2, 3, 4, 6, 16, 17, 21, 22]:
        font['name'].removeNames(nameID=name_id)
    for name_id, value in {
        1: family, 2: 'Regular', 3: family + ' 1.0',
        4: family, 6: family.replace(' ', '') + '-Regular',
    }.items():
        font['name'].setName(value, name_id, 3, 1, 0x409)
    font['OS/2'].usWeightClass = 400
    font['OS/2'].fsSelection = (font['OS/2'].fsSelection & ~33) | 64
    font['head'].macStyle &= ~3
    if 'CFF ' in font:
        cff = font['CFF '].cff
        cff.fontNames = [family.replace(' ', '') + '-Regular']
        cff.topDictIndex[0].FamilyName = family
        cff.topDictIndex[0].FullName = family
        cff.topDictIndex[0].Weight = 'Regular'
    font.flavor = 'woff2'
    font.save(ROOT / 'public/fonts' / output)
    if output == 'ticket-rail-pinyin.woff2':
        cmap = font.getBestCmap()
        advances = {chr(code): font['hmtx'][glyph][0] / font['head'].unitsPerEm for code, glyph in cmap.items() if 32 <= code < 127}
        (ROOT / 'src/data/rail-pinyin-metrics.js').write_text('// Generated by scripts/prepare-rail-fonts.py from the bundled pinyin face.\nexport const PINYIN_TRACKING = 0.115;\nexport const PINYIN_ADVANCES = ' + json.dumps(advances, ensure_ascii=True, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(output)
