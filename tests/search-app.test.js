import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { indexedDB } from 'fake-indexeddb';
import { createRecord } from '../src/model.js';
import { prepareCloud } from './helpers/cloud.js';

test('city search UI combines endpoints, preserves input, filters the timeline and selects all matches for export', async () => {
  const dom = new JSDOM('<div id="app"></div><div id="modal-root"></div><div id="toast-root"></div>', { url: 'http://localhost/' });
  const { window } = dom;
  for (const key of ['window', 'document', 'location', 'history', 'sessionStorage', 'FormData']) Object.defineProperty(globalThis, key, { value: key === 'window' ? window : window[key], configurable: true });
  Object.defineProperty(globalThis, 'navigator', { value: window.navigator, configurable: true });
  Object.defineProperty(globalThis, 'indexedDB', { value: indexedDB, configurable: true });
  window.scrollTo = () => {};
  window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  const waitFor = async fn => { for (let i = 0; i < 150; i++) { if (fn()) return; await new Promise(r => setTimeout(r, 10)); } assert.fail('Search UI did not arrive'); };
  const click = selector => { const el = document.querySelector(selector); assert.ok(el, selector); el.click(); };
  const fill = (key, value) => {
    const el = document.querySelector(`[data-search-field="${key}"]`); assert.ok(el, key);
    if (el.type === 'checkbox') el.checked = value; else el.value = value;
    el.dispatchEvent(new window.Event(el.tagName === 'SELECT' || el.type === 'checkbox' ? 'change' : 'input', { bubbles: true }));
  };
  const count = n => document.querySelector('#search-result-count')?.textContent.startsWith(`找到 ${n} 张`);
  const make = (id, extra = {}) => createRecord({ id, origin: '清河', destination: '上海虹桥', passenger: '张三', service: 'G103', departureDate: '2025-08-16', ...extra });
  const records = [...Array.from({ length: 60 }, (_, i) => make('out-' + i, { passenger: '张三' + i, departureDate: `2025-08-${String(i % 28 + 1).padStart(2, '0')}` })), make('return', { origin: '上海虹桥', destination: '北京南', departureDate: '2025-08-18', service: 'G104' }), make('other', { origin: '北京南', destination: '天津', passenger: '李四' }), make('air', { type: 'flight', template: 'air-boarding-pass', origin: 'PEK', originCode: 'PEK', destination: 'SHA', destinationCode: 'SHA', service: 'CA181', passenger: '李四', price: '100' }), make('unknown', { origin: '历史未知车站', destination: '未知终点', departureDate: '' })];
  const db = await import('../src/db.js');
  await prepareCloud(records);
  await import('../src/app.js'); await waitFor(() => count(64));
  assert.equal(document.querySelectorAll('.ticket-card').length, 48);
  assert.equal(document.querySelector('[data-action="save-search"]'), null);
  assert.equal(document.querySelector('[data-search-field="currency"]'), null);
  assert.equal(document.querySelector('.location-data-help'), null);
  assert.equal(document.querySelector('.card-template'), null);
  assert.doesNotMatch(document.querySelector('.ticket-card').textContent, /蓝色磁介质票|热敏版|长条版/);
  assert.equal(document.querySelector('[data-search-field="seat"]'), null);
  assert.equal(document.querySelector('#search-dateFrom').type,'date');assert.equal(document.querySelector('#search-dateTo').type,'date');
  assert.doesNotMatch(document.body.textContent,/城市或地点对调|日期可填年、年月或完整日期|开发预览/);
  assert.deepEqual([...document.querySelectorAll('.filter-inputs [data-search-field]')].map(input => input.dataset.searchField), ['query', 'year']);
  assert.equal(document.querySelector('[data-action="reset-filters"]').closest('details').id, 'advanced-search');
  const help = document.querySelector('.search-help'), question = help.querySelector('button'), hint = help.querySelector('p');
  const enter = new window.Event('pointerenter');
  Object.defineProperty(enter, 'pointerType', { value: 'mouse' });
  assert.equal(hint.hidden, true);
  help.dispatchEvent(enter); assert.equal(hint.hidden, false);
  help.dispatchEvent(new window.Event('pointerleave')); assert.equal(hint.hidden, true);
  question.click(); assert.equal(question.getAttribute('aria-expanded'), 'true');
  question.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert.equal(hint.hidden, true);
  document.querySelector('#advanced-search').open = true;
  fill('originCity', '北京'); fill('bothDirections', true); await waitFor(() => count(63));
  assert.match(document.querySelector('#city-context').textContent, /清河/);
  assert.match(document.querySelector('#city-context').textContent, /北京首都/);
  const input = document.querySelector('#search'); input.focus(); input.value = '北京 张三';
  input.dispatchEvent(new window.InputEvent('input', { bubbles: true, isComposing: true }));
  await new Promise(r => setTimeout(r, 170)); assert.ok(count(63));
  input.dispatchEvent(new window.CompositionEvent('compositionend', { bubbles: true })); await waitFor(() => count(61));
  assert.equal(document.querySelector('#search'), input); assert.equal(document.activeElement, input);
  fill('query', '北京 张三 -G104'); await waitFor(() => count(60));
  assert.equal(document.querySelectorAll('[data-archive-select]').length,48);
  assert.equal(document.querySelector('[data-action="export-album"]'),null);
  click('[data-archive-select-all]');await waitFor(()=>document.querySelector('.archive-selection-count').textContent.includes('60'));
  click('[data-action="export-album"]');await waitFor(()=>document.querySelector('[data-export-format="pdf"]'));
  assert.match(document.querySelector('[data-export-count]').textContent,/60/);
  assert.equal(document.querySelector('[data-export-index]'),null);
  assert.ok(document.querySelector('[name="album-title"]'));
  assert.match(document.querySelector('[data-album-summary]').textContent,/页/);
  click('[data-action="close-modal"]');
  click('[data-action="reset-filters"]'); await waitFor(() => count(64));
  document.querySelector('#advanced-search').open = true;
  fill('originCity', 'beijing'); fill('destinationCity', '上海'); await waitFor(() => count(61));
  fill('bothDirections', true); await waitFor(() => count(62));
  fill('dateFrom', '2025-08-15'); fill('dateTo', '2025-08-20'); await waitFor(() => count(14));
  click('[data-ticket-view="list"]'); await waitFor(() => document.querySelectorAll('.timeline-item').length === 14);
  click('[data-ticket-view="grid"]'); await waitFor(() => count(14));
  click('[data-action="clear-search-field"][data-field="dates"]'); await waitFor(() => count(62));
  click('[data-action="swap-route"]'); await waitFor(() => document.querySelector('#search-originCity').value === '上海');
  fill('bothDirections', false); await waitFor(() => count(1));
  click('[data-action="reset-filters"]'); await waitFor(() => count(64));
  fill('year', 'unknown'); await waitFor(() => count(1));
  fill('dateFrom','2026-01-01');fill('dateTo','2025-12-31');await waitFor(()=>!document.querySelector('#search-error').hidden);
  assert.equal(document.querySelector('[data-archive-select-all]').disabled,true);
  assert.equal(document.querySelector('[data-action="export-album"]'),null);
  assert.match(document.querySelector('.archive-selection-count').textContent,/0/);
  assert.match(document.querySelector('#search-error').textContent, /起始日期/);
  assert.equal((await db.get('records', [])).length, 64, 'searching must not alter stored ticket records');
  dom.window.close();
});
