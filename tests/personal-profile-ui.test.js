import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { indexedDB } from 'fake-indexeddb';
import { prepareCloud } from './helpers/cloud.js';
import { createRecord } from '../src/model.js';

test('optional profile saves partially, pre-fills new forms, preserves manual changes and never rewrites old tickets', async () => {
  const dom = new JSDOM('<div id="app"></div><div id="modal-root"></div><div id="toast-root"></div>',{url:'http://localhost/#data'}), {window}=dom;
  for (const key of ['window','document','location','history','sessionStorage','FormData','Image']) Object.defineProperty(globalThis,key,{value:key==='window'?window:window[key],configurable:true});
  Object.defineProperty(globalThis,'navigator',{value:window.navigator,configurable:true});
  Object.defineProperty(globalThis,'indexedDB',{value:indexedDB,configurable:true});
  window.scrollTo=()=>{}; window.confirm=()=>true;
  Object.defineProperty(globalThis,'confirm',{value:()=>true,configurable:true});
  window.HTMLDialogElement.prototype.showModal=function(){this.open=true;}; window.HTMLDialogElement.prototype.close=function(){this.open=false;};
  const old=createRecord({id:'old-ticket',origin:'北京南',destination:'天津',service:'C2021',departureDate:'2023-05-26',passenger:'历史姓名',identity:'000000********1234'});
  const server=await prepareCloud([old],{flightMcpKey:'keep-this-key'}), db=await import('../src/db.js');
  const wait=async fn=>{for(let i=0;i<400;i++){if(await fn())return;await new Promise(r=>setTimeout(r,10));}assert.fail('Profile UI did not settle');};
  const click=selector=>{const button=document.querySelector(selector);assert.ok(button,selector);button.click();};
  const fill=(selector,value,event='input')=>{const input=document.querySelector(selector);assert.ok(input,selector);input.value=value;input.dispatchEvent(new window.Event(event,{bubbles:true}));};
  const go=async page=>{click(`[data-action=navigate][data-page=${page}]`);await wait(()=>document.querySelector(page==='data'?'#profile-form':'.ticket-card'));};
  const save=async check=>{document.querySelector('#profile-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await wait(async()=>check()&&!(await db.get('syncMeta')).pending&&!document.querySelector('#profile-form [type=submit]').disabled);};
  await import('../src/app.js'); await wait(()=>document.querySelector('#profile-form [name=chineseName]')?.disabled===false);
  assert.equal(document.querySelector('#profile-form [required]'),null);
  assert.equal(document.querySelector('#profile-form [name=birthDate],#profile-form [name=phone],#profile-form [name=personalInfo],#profile-form [name=nationality],#profile-form [data-doc-field=country]'),null);
  fill('#profile-form [name=chineseName]','示例旅客');
  await save(()=>server.settings().profile?.chineseName==='示例旅客');
  assert.equal(server.settings().profile.firstName,''); assert.equal(server.settings().profile.lastName,''); assert.equal(server.settings().profile.documents.length,0);
  assert.equal(server.settings().flightMcpKey,'keep-this-key'); assert.deepEqual(server.records(),[old]);
  await go('archive'); click('[data-action=new]'); await wait(()=>document.querySelector('#editor-form'));
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'示例旅客');
  assert.equal(document.querySelector('#editor-form [name=identity]').value,'');
  fill('#editor-form [name=type]','flight');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'');
  click('[data-action=close-modal]'); await go('data');
  fill('#profile-form [name=firstName]','San');
  fill('#profile-form [name=lastName]','zhang');
  assert.equal(document.querySelector('#profile-form [name=firstName]').value,'SAN');
  assert.equal(document.querySelector('#profile-form [name=lastName]').value,'ZHANG');
  fill('#profile-form [name=gender]','男','change');
  click('[data-profile-add]');
  fill('#profile-form [data-doc-field=type]','passport','change');
  fill('#profile-form [data-doc-field=number]','E00000000');
  await save(()=>server.settings().profile?.documents[0]?.number==='E00000000');
  const number = document.querySelector('#profile-form [data-doc-field=number]');
  assert.equal(number.value,'E000000**');
  assert.equal(number.getAttribute('value'),'E000000**');
  assert.match(document.querySelector('#profile-form [name=flightDocument]').textContent,/E000000\*\*/);
  number.focus();
  assert.equal(number.value,'E00000000');
  fill('#profile-form [data-doc-field=number]','E00000012');
  number.blur();
  assert.equal(number.value,'E000000**');
  await save(()=>server.settings().profile?.documents[0]?.number==='E00000012');
  document.querySelector('#profile-form [data-doc-field=number]').focus();
  fill('#profile-form [data-doc-field=number]','E00000000');
  document.querySelector('#profile-form [data-doc-field=number]').blur();
  await save(()=>server.settings().profile?.documents[0]?.number==='E00000000');
  await go('archive'); click('[data-action=new]'); await wait(()=>document.querySelector('#editor-form'));
  fill('#editor-form [name=type]','flight');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'ZHANG/SAN');
  assert.equal(document.querySelector('#editor-form [name=identity]').value,'E00000000');
  fill('#editor-form [name=origin]','PEK');fill('#editor-form [name=destination]','SHA');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'示例旅客');assert.equal(document.querySelector('#editor-form [name=identity]').value,'');
  assert.equal(document.querySelector('[data-bcbp="passenger"]').value,'ZHANG/SAN');
  fill('#editor-form [name=destination]','LHR');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'ZHANG/SAN');assert.equal(document.querySelector('#editor-form [name=identity]').value,'E00000000');
  assert.equal(document.querySelector('[data-bcbp="passenger"]'),null);
  assert.equal(document.querySelector('#editor-form [name=nationality],#editor-form [name=gender],#editor-form [name=identityType]'),null);
  fill('#editor-form [name=passenger]','zhang/San-Ming');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'ZHANG/SAN-MING');
  fill('#editor-form [name=passenger]','单票姓名'); fill('#editor-form [name=identity]','P000001');
  fill('#editor-form [name=origin]','PEK'); fill('#editor-form [name=destination]','LHR'); fill('#editor-form [name=service]','CA937'); fill('#editor-form [name=departureDate]','2026-11-16');fill('#editor-form [name=departureTime]','12:00');fill('#editor-form [name=seat]','24K');fill('#editor-form [name=seatClass]','Y');
  document.querySelector('#editor-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await wait(()=>!document.querySelector('dialog')&&server.records().length===2);
  assert.equal(server.records().find(r=>r.id!=='old-ticket').passenger,'单票姓名');
  assert.equal(server.records().find(r=>r.id!=='old-ticket').identity,'P000001');
  assert.deepEqual(server.records().find(r=>r.id==='old-ticket'),old);
  await go('archive'); click('[data-action=view][data-id="old-ticket"]');await wait(()=>document.querySelector('[data-action=edit]'));click('[data-action=edit]');await wait(()=>document.querySelector('#editor-form'));
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'历史姓名');
  assert.equal(document.querySelector('#editor-form [name=nationality],#editor-form [name=gender],#editor-form [name=identityType],#editor-form .personal-ticket-fields'),null);
  click('[data-action=close-modal]');await wait(()=>!document.querySelector('dialog'));click('[data-action=new]');await wait(()=>document.querySelector('#editor-form'));
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'示例旅客');
  fill('#editor-form [name=type]','flight');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'ZHANG/SAN');
  assert.equal(document.querySelector('#editor-form [name=identity]').value,'E00000000');
  fill('#editor-form [name=passenger]','单独修改'); fill('#editor-form [name=type]','rail');
  assert.equal(document.querySelector('#editor-form [name=passenger]').value,'示例旅客');
  assert.equal(document.querySelector('#editor-form [name=identity]').value,'');
  click('[data-action=close-modal]');await wait(()=>!document.querySelector('dialog'));await go('data');
  const before=server.settings().profile;
  fill('#flight-form [name=key]','changed-key');document.querySelector('#flight-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await wait(()=>server.settings().flightMcpKey==='changed-key'&&!document.querySelector('#flight-form [name=key]').disabled);
  assert.deepEqual(server.settings().profile,before);
  for(const key of ['chineseName','firstName','lastName','gender'])fill(`#profile-form [name=${key}]`,'');
  click('[data-profile-remove]');
  await save(()=>!server.settings().profile);
  await go('archive');click('[data-action=new]');await wait(()=>document.querySelector('#editor-form'));assert.equal(document.querySelector('#editor-form [name=passenger]').value,'');assert.equal(document.querySelector('#editor-form [name=identity]').value,'');
  dom.window.close();
});
