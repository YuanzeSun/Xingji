import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { indexedDB } from 'fake-indexeddb';
import { prepareCloud } from './helpers/cloud.js';

test('manual entry always previews, validates required fields and resolves airport codes and zones automatically', async () => {
  const dom = new JSDOM('<div id="app"></div><div id="modal-root"></div><div id="toast-root"></div>', { url: 'http://localhost/#archive' }), { window } = dom;
  for (const key of ['window','document','location','history','sessionStorage','FormData','Image']) Object.defineProperty(globalThis,key,{value:key==='window'?window:window[key],configurable:true});
  Object.defineProperty(globalThis,'navigator',{value:window.navigator,configurable:true});
  Object.defineProperty(globalThis,'indexedDB',{value:indexedDB,configurable:true});
  window.scrollTo=()=>{}; globalThis.confirm=()=>true;
  window.HTMLDialogElement.prototype.showModal=function(){this.open=true;}; window.HTMLDialogElement.prototype.close=function(){this.open=false;};
  const wait=async fn=>{for(let i=0;i<300;i++){if(await fn())return;await new Promise(r=>setTimeout(r,10));}assert.fail('Editor did not settle');};
  const click=selector=>{const el=document.querySelector(selector);assert.ok(el,selector);el.click();};
  const fill=(name,value)=>{const input=document.querySelector(`#editor-form [name="${name}"]`);assert.ok(input,name);input.value=value;input.dispatchEvent(new window.Event('input',{bubbles:true}));};
  const submit=()=>document.querySelector('#editor-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  const requiredHint=()=>document.querySelector('.modal-heading .editor-required-hint');
  const db=await import('../src/db.js'); await prepareCloud();
  await import('../src/app.js'); await wait(()=>document.querySelector('[data-action=new]:not(:disabled)'));
  assert.equal(document.querySelector('#manual-form'),null);
  click('[data-action="new"]'); await wait(()=>document.querySelector('#editor-preview'));
  assert.deepEqual([...requiredHint().children].map(note=>note.textContent),['* 保存必填','* 生成二维码必填']);
  assert.equal(requiredHint().querySelector('.barcode-required-mark').getAttribute('aria-label'),'蓝色星号');
  assert.equal(document.querySelector('.editor-fields details:not(.rail-start-override):not(.rail-lookup-result):not([data-rail-photo-entry])'),null);
  assert.equal(document.querySelector('[data-rail-photo-entry]').open,false);
  assert.equal(document.querySelector('[data-rail-photo-entry] > summary').firstChild.textContent.trim(), '扫描票面（alpha）');
  assert.equal(document.querySelector('[data-code-editor]').tagName,'SECTION');
  const ticketOptions=document.querySelector('.rail-ticket-options');
  assert.equal(document.querySelector('[data-rail-photo-entry]').nextElementSibling,ticketOptions);
  assert.ok(ticketOptions.querySelector('[name="template"]'));
  assert.ok(ticketOptions.querySelector('[data-refund-receipt]'));
  assert.ok(ticketOptions.querySelector('[data-rail-standing]'));
  assert.equal(document.querySelector('[name="template"]').value,'rail-receipt');
  assert.equal(document.querySelector('[name="departureDateYear"]').type,'number');
  const identity = document.querySelector('[name="identity"]');
  const star = new window.InputEvent('beforeinput', { data: '＊', inputType: 'insertText', bubbles: true, cancelable: true });
  assert.equal(identity.dispatchEvent(star), false);
  fill('identity','0000002000****1234');
  assert.equal(identity.value, '');
  for(const name of ['origin','destination','service','departureDate','departureTime','passenger','identity','carriage','seat']){
    const input=name==='seat'?document.querySelector('[data-seat-number]'):document.querySelector(`[name="${name}"]`);
    assert.equal(input.required,true);
    assert.ok(document.querySelector(`[name="${name}"]`).closest('.field').querySelector('.required-mark'));
  }
  assert.equal(document.querySelector('.optional-mark'),null);assert.equal(document.querySelector('[name="provenance"]'),null);assert.equal(document.querySelector('[name="arrivalTime"]').type,'time');assert.equal(document.querySelector('[name="arrivalDateYear"]').type,'number');assert.equal(document.querySelector('[data-seat-preset]').required,true);
  submit();await wait(()=>document.querySelector('#editor-error').textContent.includes('出发'));
  fill('origin','清河');fill('destination','天津');fill('service','G103');fill('departureDate','2025-02-29');fill('departureTime','08:00');fill('passenger','示例旅客');fill('identity','000000200001011234');fill('carriage','05');fill('seat','08F');fill('seatClass','二等座');
  submit();await wait(()=>document.querySelector('#editor-error').textContent.includes('日期'));
  assert.deepEqual(await db.get('records',[]),[]);
  fill('departureDate','2026-11-15');fill('departureTime','08:00');fill('passenger','示例旅客');fill('carriage','05');fill('seatClass','二等座');fill('identity','000000200001011234');fill('gate','5B');fill('seat','08F');fill('orderNumber','E000000001');
  assert.match(document.querySelector('#editor-preview').textContent,/0000002000\*{4}1234/);
  submit();await wait(()=>!document.querySelector('dialog'));
  let records=await db.get('records',[]);assert.equal(records.length,1);assert.equal(records[0].gate,'5B');assert.equal(records[0].orderNumber,'E000000001');
  const startSupplement = async () => {
    click('[data-action="new"]');await wait(()=>document.querySelector('#editor-form'));
    fill('origin','清河');fill('destination','天津');fill('service','G103');fill('departureDate','2026-11-15');fill('departureTime','08:00');fill('passenger','示例旅客');fill('carriage','05');fill('seatClass','二等座');fill('identity','000000200001011234');fill('seat','08F');fill('price','100');
  };
  await startSupplement();
  submit();await wait(()=>document.querySelector('.duplicate-dialog'));
  assert.match(document.querySelector('.duplicate-dialog').textContent,/票价.*100/);
  assert.equal((await db.get('records',[]))[0].price,'');
  document.querySelector('.duplicate-dialog').dispatchEvent(new window.Event('cancel',{cancelable:true}));
  await wait(()=>!document.querySelector('dialog'));
  assert.equal((await db.get('records',[]))[0].price,'');
  await startSupplement();
  submit();await wait(()=>document.querySelector('.duplicate-dialog'));
  click('.duplicate-dialog [data-duplicate-value]:not([data-duplicate-value=""])');await wait(()=>!document.querySelector('dialog'));
  records=await db.get('records',[]);assert.equal(records.length,1);assert.equal(records[0].price,'100');assert.equal(records[0].seat,'08F');
  click('[data-action="new"]');await wait(()=>document.querySelector('#editor-form'));
  fill('type','flight');fill('passenger','示例旅客');fill('identity','P000001');fill('seat','24K');fill('seatClass','Y');fill('departureTime','12:00');assert.match(document.querySelector('[name="seat"]').closest('.field').textContent.trim(),/^座位号\*/);assert.equal(document.querySelector('[data-field-source="seat"]').textContent,'手动输入');
  assert.deepEqual([...requiredHint().children].map(note=>note.textContent),['* 保存必填','* 生成条码必填']);
  assert.equal(document.querySelector('[name="originCode"]').type,'hidden');
  assert.equal(document.querySelector('[name="departureZone"], [name="arrivalZone"]'),null);
  const origin=document.querySelector('#editor-form [name="origin"]');origin.focus();fill('origin','ｐｅｋ');
  assert.equal(origin.getAttribute('aria-expanded'),'true');
  origin.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
  assert.equal(document.querySelector('[name="originCode"]').value,'PEK');
  fill('destination','JFK');fill('service','CA981');fill('departureDate','2026-07-01');
  fill('destination','LHR');assert.equal(document.querySelector('[name="destinationCode"]').value,'LHR');
  fill('destination','没有这个机场');assert.equal(document.querySelector('[name="destinationCode"]').value,'');
  const destination=document.querySelector('#editor-form [name="destination"]');destination.focus();fill('destination','CSG');
  destination.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
  destination.dispatchEvent(new window.Event('change',{bubbles:true}));
  assert.equal(document.querySelector('[name="destinationCode"]').value,'CSG','a selected IATA code must survive a shared English airport name');
  fill('destination','HND');fill('aircraft','Airbus A330-300');fill('aircraftRegistration','B-0002');
  assert.match(document.querySelector('#editor-preview').textContent,/A330-300/);
  submit();await wait(()=>!document.querySelector('dialog'));
  const flight=(await db.get('records',[])).find(r=>r.type==='flight');
  assert.equal(flight.originCode,'PEK');assert.equal(flight.destinationCode,'HND');
  assert.equal(flight.departureZone,'Asia/Shanghai');assert.equal(flight.arrivalZone,'Asia/Tokyo');
  assert.equal(document.querySelector('#city-reference'),null);
  click('[data-action="new"]');await wait(()=>document.querySelector('#editor-form'));
  const railOrigin=document.querySelector('[name="origin"]');railOrigin.focus();fill('origin','beijingnan');
  assert.equal(railOrigin.getAttribute('aria-expanded'),'true');
  railOrigin.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
  assert.equal(railOrigin.value,'北京南');
  const controls=[...document.querySelectorAll('#editor-form input,#editor-form select')];
  assert.ok(controls.indexOf(document.querySelector('[data-seat-preset]'))<controls.indexOf(document.querySelector('[data-seat-number]')));
  const template=document.querySelector('[name="template"]');assert.equal([...template.options].some(option=>option.value==='rail-refund-receipt'),false);
  click('[data-rail-standing]');
  click('[data-refund-receipt]');
  assert.equal(document.querySelector('[name="template"]').value,'rail-receipt');
  assert.equal(document.querySelector('[data-refund-receipt]').checked,true);
  assert.equal(document.querySelector('[data-rail-standing]').checked,true);
  assert.equal(document.querySelector('[name="seat"]'),null);
  click('[data-rail-standing]');
  assert.equal(document.querySelector('[data-refund-receipt]').checked,true);
  assert.ok(document.querySelector('[name="seat"]'));
  click('[data-rail-standing]');
  assert.equal(document.querySelector('[data-rail-standing]').checked,true);
  assert.match(document.querySelector('#editor-preview').textContent,/无座.*退票费/s);
  assert.equal(document.querySelector('[name="price"]').required,true);assert.equal(document.querySelector('[name="departureTime"]').required,false);
  fill('destination','天津');fill('service','C123');fill('departureDate','2026-11-17');fill('passenger','示例旅客');fill('identity','000000200001011234');fill('price','20');
  submit();await wait(()=>!document.querySelector('dialog'));
  const refund=(await db.get('records',[])).find(record=>record.template==='rail-refund-receipt');assert.equal(refund.price,'20');
  assert.equal(refund.railStanding,true);assert.equal(refund.seat,'');
  dom.window.close();
});
