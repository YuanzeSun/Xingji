import test from 'node:test';
import assert from 'node:assert/strict';
import { createRecord } from '../src/model.js';
import { MemoryGitHub } from './helpers/cloud.js';
import { D1Store } from '../src/d1.js';
import { GitHubStore } from '../src/github.js';
import { backUpToGitHub, publishCloudLink } from '../src/archive-migration.js';
import { memoryD1, endpoint, token } from './helpers/d1.js';
import { answerArithmetic } from './helpers/arithmetic.js';
import { browser, until, connect, chooseSource, confirm, useServers } from './helpers/d1-app.js';

test('D1-first binding can keep GitHub data and one reset clears both archives', async () => {
  const window = browser();
  const github = new MemoryGitHub([createRecord({ id: 'github-original', service: 'G21' })],
    { flightMcpKey: 'github-mcp', profile: { chineseName: 'GitHub passenger' } });
  const d1 = memoryD1([createRecord({ id: 'd1-original', service: 'G103' })],
    { flightMcpKey: 'old-d1-mcp' });
  useServers(github, d1);
  const reset = () => document.querySelector('[data-action="reset-repository"]');
  const d1Records = () => d1.sqlite.prepare('SELECT id FROM tickets ORDER BY id').all().map(record => record.id);
  const d1Settings = () => JSON.parse(d1.sqlite.prepare('SELECT settings FROM archive_state').get().settings);
  try {
    await import('../src/app.js');
    await until(() => document.querySelector('#d1-form'));
    const firstForm = document.querySelector('#d1-form');
    connect(window, 'd1');
    await until(() => document.querySelector('[data-d1-cloud-label]')?.textContent === '已同步');
    assert.equal(document.querySelector('#d1-form'), null);
    const before = d1.calls.length;
    firstForm.dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
    assert.equal(d1.calls.length, before);

    const unpairedHead = github.head;
    connect(window, 'github');
    await chooseSource('github');
    await confirm('确认覆盖 D1');
    await until(() => document.querySelector('[data-action="backup-github"]')?.disabled === false);
    assert.notEqual(github.head, unpairedHead);
    assert.deepEqual(github.records().map(row => row.id), ['github-original']);
    assert.deepEqual(d1Records(), ['github-original']);
    assert.equal(d1Settings().flightMcpKey, 'github-mcp');
    assert.equal(d1Settings().connections.d1.token, token);
    assert.deepEqual(github.settings().connections, d1Settings().connections);

    assert.equal(document.querySelector('[data-action="disconnect-d1"], [data-action="disconnect"]'), null);
    assert.ok(document.querySelector('[data-action="disconnect-all"]'));
    assert.equal(document.querySelectorAll('[data-action="reset-repository"]').length, 1);

    const beforeD1Settings = d1Settings(), beforeGitHubSettings = github.settings();
    reset().click();
    await until(() => document.querySelector('[data-archive-reset]'));
    assert.match(document.querySelector('.reset-targets').textContent, /GitHub.*D1/s);
    const form = document.querySelector('[data-archive-reset]');
    form.elements['confirm-reset'].click();
    answerArithmetic(document);
    d1.sqlite.exec("CREATE TRIGGER block_reset BEFORE DELETE ON tickets BEGIN SELECT RAISE(ABORT, 'blocked'); END");
    form.querySelector('[type="submit"]').click();
    await until(() => form.querySelector('[data-reset-error]').textContent.includes('GitHub 已重置'));
    assert.deepEqual(github.records(), []);
    assert.deepEqual(d1Records(), ['github-original']);
    const afterGitHubReset = github.head;

    d1.sqlite.exec('DROP TRIGGER block_reset');
    form.querySelector('[type="submit"]').click();
    await until(() => !document.querySelector('dialog') && document.querySelector('h1')?.textContent === '我的票据');
    assert.equal(github.head, afterGitHubReset, 'a retry must not reset a completed GitHub archive twice');
    assert.deepEqual(d1Records(), []);
    assert.deepEqual(github.settings(), beforeGitHubSettings);
    assert.deepEqual(d1Settings(), beforeD1Settings);

    document.querySelector('[data-action="navigate"][data-page="data"]').click();
    await until(reset);
    reset().click();
    await until(() => document.querySelector('[data-archive-reset]'));
    const unlinkForm = document.querySelector('[data-archive-reset]');
    const keep = unlinkForm.querySelector('[data-keep-cloud]');
    assert.equal(keep.hidden, true);
    unlinkForm.elements['unlink-clouds'].click();
    assert.equal(keep.hidden, false);
    unlinkForm.elements['confirm-reset'].click();
    answerArithmetic(document);
    const writesBeforeChoice = d1.calls.filter(call => call.method === 'POST').length;
    unlinkForm.querySelector('[type="submit"]').click();
    assert.equal(d1.calls.filter(call => call.method === 'POST').length, writesBeforeChoice);
    keep.querySelector('[value="github"]').click();
    unlinkForm.querySelector('[type="submit"]').click();
    await until(() => !document.querySelector('dialog') && document.querySelector('h1')?.textContent === '我的票据');
    const db = await import('../src/db.js');
    assert.equal((await db.get('github')).id, 77);
    assert.equal(await db.get('d1', null), null);
    assert.equal(sessionStorage.getItem('xingji-d1-token'), null);
    assert.equal(await db.get('d1Token'), '');
    assert.equal(await db.get('githubToken'), 'github-credential');
    assert.deepEqual(github.settings(), { ...beforeGitHubSettings, connections: { unlinked: true } });
    assert.deepEqual(d1Settings(), { ...beforeD1Settings, connections: { unlinked: true } });
    const id = d1.sqlite.prepare('SELECT id FROM archive_state').get().id;
    const oldD1 = new D1Store({ id, url: endpoint }, token);
    const oldGithub = new GitHubStore({ id: 77, owner: 'user', repo: 'data', branch: 'main' }, 'github-credential');
    const unlinkedHead = github.head;
    await assert.rejects(backUpToGitHub(oldD1, oldGithub), /关联已解除/);
    await assert.rejects(publishCloudLink(oldGithub, oldD1), /关联已解除/);
    assert.equal(github.head, unlinkedHead);

    document.querySelector('[data-action="navigate"][data-page="data"]').click();
    await until(() => document.querySelector('[data-action="disconnect"]'));
    document.querySelector('[data-action="disconnect"]').click();
    await until(() => document.querySelector('.cloud-setup #d1-form'));
    connect(window, 'd1');
    await until(() => document.querySelector('[data-d1-cloud-label]')?.textContent === '已同步');
    assert.equal(await db.get('github', null), null, 'a new D1 login does not restore the severed GitHub association');
    assert.equal(document.querySelector('[data-action="disconnect-all"]'), null);
    connect(window, 'github');
    await chooseSource('d1');
    await confirm('确认覆盖 GitHub');
    await until(() => document.querySelector('[data-action="backup-github"]')?.disabled === false);
    reset().click();
    await until(() => document.querySelector('[data-archive-reset]'));
    const keepD1Form = document.querySelector('[data-archive-reset]');
    keepD1Form.elements['unlink-clouds'].click();
    keepD1Form.querySelector('[name="keep-cloud"][value="d1"]').click();
    keepD1Form.elements['confirm-reset'].click();
    answerArithmetic(document);
    d1.loseAcknowledgement = true;
    keepD1Form.querySelector('[type="submit"]').click();
    await until(() => keepD1Form.querySelector('[data-reset-error]').textContent.includes('D1 重置尚未完成'));
    assert.deepEqual(d1Settings().connections, { unlinked: true });
    const resets = d1.calls.filter(call => call.method === 'POST').length;
    keepD1Form.querySelector('[type="submit"]').click();
    await until(() => !document.querySelector('dialog') && document.querySelector('h1')?.textContent === '我的票据');
    assert.equal(d1.calls.filter(call => call.method === 'POST').length, resets);
    assert.equal((await db.get('d1')).id, id);
    assert.equal(await db.get('github', null), null);
    assert.equal(sessionStorage.getItem('xingji-github-token'), null);
    assert.equal(await db.get('githubToken'), '');
    assert.equal(await db.get('d1Token'), token);
  } finally { window.dispatchEvent(new window.Event('offline')); window.close(); }
});
